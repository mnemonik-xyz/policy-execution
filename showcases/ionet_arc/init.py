#!/usr/bin/env python3
"""Initialize public keys and sign VendorCredential using authority keys and manifest parameters."""

import argparse
import contextlib
import datetime
import json
import os
import pathlib
import re
import secrets
import subprocess
import sys
import tempfile
import time

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]


def dump_yaml(data: any) -> str:
    return yaml.dump(data, sort_keys=False, default_flow_style=False)


def annotate_timestamps(text: str, valid_after: int, valid_until: int) -> str:
    after_str = datetime.datetime.fromtimestamp(valid_after, tz=datetime.UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    until_str = datetime.datetime.fromtimestamp(valid_until, tz=datetime.UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    text = re.sub(rf"(valid_after:\s*{valid_after})(?!\s*#)", rf"\1  # {after_str}", text)
    text = re.sub(rf"(valid_until:\s*{valid_until})(?!\s*#)", rf"\1  # {until_str}", text)
    return text


def to_hex(data: list[int] | bytes) -> str:
    return "0x" + bytes(data).hex()


def from_hex(hex_str: str) -> list[int]:
    raw = hex_str.strip().lower()
    if raw.startswith("0x"):
        raw = raw[2:]
    return list(bytes.fromhex(raw))


def find_binary(name: str) -> pathlib.Path:
    for candidate in [
        REPO_ROOT / "target" / "release" / name,
        REPO_ROOT / "target" / "debug" / name,
    ]:
        if candidate.exists() and candidate.is_file():
            return candidate
    raise FileNotFoundError(
        f"Could not find compiled binary '{name}'. Run 'cargo build --release -p warrant-host'."
    )


def ensure_key_file(path: pathlib.Path, force: bool = False) -> str:
    if path.exists() and not force:
        content = path.read_text().strip()
        if content:
            return content
    key_hex = secrets.token_hex(32)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(key_hex + "\n")
    with contextlib.suppress(Exception):
        os.chmod(path, 0o600)
    return key_hex


def get_public_key_hex(evidence_bin: pathlib.Path, key_path: pathlib.Path) -> str:
    res = subprocess.run(
        [str(evidence_bin), "public-key", str(key_path)],
        capture_output=True,
        text=True,
        check=True,
    )
    raw_bytes = json.loads(res.stdout.strip())
    return to_hex(raw_bytes)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Initialize public_keys.yaml and sign VendorCredential using parameters from manifest.yaml."
    )
    parser.add_argument(
        "--manifest",
        type=pathlib.Path,
        default=REPO_ROOT / "showcases" / "ionet_arc" / "config" / "manifest.yaml",
        help="Path to manifest.yaml config (default: showcases/ionet_arc/config/manifest.yaml)",
    )
    parser.add_argument(
        "--force-key",
        action="store_true",
        help="Regenerate authority private keys if present",
    )
    args = parser.parse_args()

    manifest_path = args.manifest.resolve()
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest file not found: {manifest_path}")

    with manifest_path.open() as f:
        manifest = yaml.safe_load(f)

    chain_id = manifest["chain_id"]
    escrow_addr = manifest["escrow_address"]
    token_addr = manifest["token_address"]
    seller_addr = manifest["seller_address"]
    category = manifest["category"]
    validity_days = int(manifest.get("vendor_validity_days", 365))
    keys_dir = REPO_ROOT / "showcases" / "ionet_arc" / ".keys"
    keys_dir.mkdir(parents=True, exist_ok=True)
    with contextlib.suppress(Exception):
        os.chmod(keys_dir, 0o700)

    reg_key_rel = manifest.get("private_key_files", {}).get("registry_key", "showcases/ionet_arc/.keys/registry.key")
    reg_key_path = REPO_ROOT / reg_key_rel
    ensure_key_file(reg_key_path, force=args.force_key)

    acc_key_rel = manifest.get("private_key_files", {}).get(
        "buyer_acceptance_key", "showcases/ionet_arc/.keys/buyer_acceptance.key"
    )
    acc_key_path = REPO_ROOT / acc_key_rel
    ensure_key_file(acc_key_path, force=args.force_key)

    evidence_bin = find_binary("warrant-evidence")
    reg_pub_hex = get_public_key_hex(evidence_bin, reg_key_path)
    acc_pub_hex = get_public_key_hex(evidence_bin, acc_key_path)

    pub_keys_rel = manifest.get("public_files", {}).get(
        "public_keys", "showcases/ionet_arc/config/public_keys.yaml"
    )
    public_keys_yaml_path = REPO_ROOT / pub_keys_rel
    public_keys_yaml_path.parent.mkdir(parents=True, exist_ok=True)
    pub_keys_header = (
        "# Authority public keys (compressed secp256k1, 33 bytes)\n"
        "# Generated by init.py from authority private keys.\n"
    )
    public_keys_obj = {
        "registry_key": reg_pub_hex,
        "buyer_acceptance_key": acc_pub_hex,
    }
    public_keys_yaml_path.write_text(pub_keys_header + dump_yaml(public_keys_obj))

    now = int(time.time())
    cred_valid_after = now - 3600
    cred_valid_until = now + (validity_days * 86400)

    credential_yaml_obj = {
        "scope": {
            "chain_id": chain_id,
            "vault": escrow_addr,
            "token": token_addr,
        },
        "recipient": seller_addr,
        "category": category,
        "valid_after": cred_valid_after,
        "valid_until": cred_valid_until,
    }

    cred_rel = manifest.get("public_files", {}).get(
        "vendor_credential", "showcases/ionet_arc/config/vendor_credential.yaml"
    )
    sig_rel = manifest.get("public_files", {}).get(
        "vendor_signature", "showcases/ionet_arc/config/vendor_signature.yaml"
    )

    credential_yaml_path = REPO_ROOT / cred_rel
    signature_yaml_path = REPO_ROOT / sig_rel
    credential_yaml_path.parent.mkdir(parents=True, exist_ok=True)
    signature_yaml_path.parent.mkdir(parents=True, exist_ok=True)

    cred_header = (
        f"# Vendor credential attesting seller category {category} accreditation.\n"
        "# Re-verified in zkVM during settlement against registry_key.\n"
    )
    raw_cred_yaml = dump_yaml(credential_yaml_obj)
    annotated_cred = annotate_timestamps(raw_cred_yaml, cred_valid_after, cred_valid_until)
    credential_yaml_path.write_text(cred_header + annotated_cred)

    credential_rust_obj = {
        "scope": {
            "chain_id": chain_id,
            "vault": from_hex(escrow_addr),
            "token": from_hex(token_addr),
        },
        "recipient": from_hex(seller_addr),
        "category": category,
        "valid_after": cred_valid_after,
        "valid_until": cred_valid_until,
    }

    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp_path = pathlib.Path(tmp_dir)
        temp_cred = tmp_path / "cred.json"
        temp_sig = tmp_path / "sig.json"
        temp_cred.write_text(json.dumps(credential_rust_obj))

        subprocess.run(
            [
                str(evidence_bin),
                "sign-vendor",
                str(reg_key_path),
                str(temp_cred),
                str(temp_sig),
            ],
            check=True,
        )
        sig_bytes = json.loads(temp_sig.read_text())
        sig_hex = to_hex(sig_bytes)
        sig_header = "# 64-byte ECDSA signature of vendor_credential.yaml signed by registry.key.\n"
        signature_yaml_path.write_text(sig_header + dump_yaml({"signature": sig_hex}))

    summary = {
        "init": {
            "status": "success",
            "manifest": str(manifest_path.relative_to(REPO_ROOT)),
            "seller_address": seller_addr,
            "category": category,
            "public_keys_file": str(public_keys_yaml_path.relative_to(REPO_ROOT)),
            "public_keys": {
                "registry_key": reg_pub_hex,
                "buyer_acceptance_key": acc_pub_hex,
            },
            "credential_file": str(credential_yaml_path.relative_to(REPO_ROOT)),
            "signature_file": str(signature_yaml_path.relative_to(REPO_ROOT)),
            "validity_days": validity_days,
        }
    }
    print(dump_yaml(summary).strip())
    return 0


if __name__ == "__main__":
    sys.exit(main())
